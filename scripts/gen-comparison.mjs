#!/usr/bin/env node
/**
 * Genera detailed A vs B comparison recipe MDX.
 * Использование: node scripts/gen-comparison.mjs cursor cline
 *
 * Собирает структурированную часть из tool-данных и генерирует MDX-stub
 * с разделами TL;DR, side-by-side, when-to-pick, FAQ — заготовку для
 * человеческой правки. Это драфт, не финал — ставится в pipeline на ревью.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { listTools, readState, writeState, recordRun, ROOT_DIR } from './_state.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function slug(s) { return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''); }

async function main() {
  const [, , aSlug, bSlug] = process.argv;
  if (!aSlug || !bSlug) {
    console.error('Usage: gen-comparison.mjs <toolA-slug> <toolB-slug>');
    process.exit(1);
  }

  const tools = await listTools();
  const a = tools.find((t) => t.slug === aSlug);
  const b = tools.find((t) => t.slug === bSlug);
  if (!a || !b) {
    console.error(`Tool not found. Available: ${tools.map((t) => t.slug).join(', ')}`);
    process.exit(1);
  }

  const filename = `${a.slug}-vs-${b.slug}-deep-dive.mdx`;
  const filepath = path.join(ROOT_DIR, 'src/content/recipes', filename);

  // Уже существует?
  try {
    await fs.access(filepath);
    console.error(`✗ Already exists: ${filepath}. Delete or pick another pair.`);
    process.exit(1);
  } catch {}

  const today = new Date().toISOString().slice(0, 10);
  const md = `---
title: "${a.name} vs ${b.name} — deep dive (when to pick which)"
description: "Honest, structured comparison of ${a.name} and ${b.name}. Pricing, models, integrations, real-world fit."
tools: ["${a.slug}", "${b.slug}"]
difficulty: "beginner"
time_minutes: 8
tags: ["comparison", "decision"]
updated: "${today}"
---

> **Draft generated by gen-comparison ${today}.**
> Hand-edit before publish — add real anecdotes, remove the "TODO" markers.

## TL;DR

- **Pick ${a.name} if**: ${a.best_for[0] ?? 'TODO add'}.
- **Pick ${b.name} if**: ${b.best_for[0] ?? 'TODO add'}.
- **Both** are good. The wrong choice costs you a few weeks, not your career.

## Side-by-side

| | ${a.name} | ${b.name} |
|---|---|---|
| Category | ${a.category} | ${b.category} |
| Pricing | ${priceLabel(a.pricing)} | ${priceLabel(b.pricing)} |
| Open source | ${a.open_source ? 'Yes' : 'No'} | ${b.open_source ? 'Yes' : 'No'} |
| Models | ${a.models_supported.slice(0,3).join(', ')} | ${b.models_supported.slice(0,3).join(', ')} |
| Best for (1) | ${a.best_for[0] ?? '—'} | ${b.best_for[0] ?? '—'} |

## When ${a.name} wins

${(a.pros ?? []).map((p) => `- ${p}`).join('\n') || '- TODO add real-world wins'}

## When ${b.name} wins

${(b.pros ?? []).map((p) => `- ${p}`).join('\n') || '- TODO'}

## Honest weaknesses

### ${a.name}'s
${(a.cons ?? []).map((c) => `- ${c}`).join('\n')}

### ${b.name}'s
${(b.cons ?? []).map((c) => `- ${c}`).join('\n')}

## Decision tree

If you find yourself doing more **${a.category} work** day-to-day, default to ${a.name}.
If you're deeper into **${b.category} workflows**, ${b.name} fits better.

For most working engineers in 2026 the answer is: **install both for a week**, see which one you reach for unconsciously, drop the other.

## FAQ

**Q: Can I run them side-by-side?**
A: Yes. They don't conflict. Most senior engineers run multiple AI tools layered.

**Q: Will I waste money paying for both?**
A: At ~$30-60/mo combined, if AI tools save you even 30 min/week, ROI is positive. See [budget guide](/recipes/spending-budget-on-ai-tools).

**Q: Which has the better community?**
A: TODO — fact-check active subreddit/Discord/Twitter sizes before publishing.

---

_Last refreshed ${today}. Sources: [${a.name}](${a.homepage}), [${b.name}](${b.homepage})._
`;

  function priceLabel(p) {
    if (p.free_tier && !p.paid_from_usd) return 'Free';
    if (p.free_tier && p.paid_from_usd) return `Free + $${p.paid_from_usd}/mo`;
    if (p.paid_from_usd) return `$${p.paid_from_usd}/mo`;
    return 'Paid';
  }

  await fs.writeFile(filepath, md, 'utf-8');

  // Регистрируем в state.pipeline.drafts
  const state = await readState();
  state.pipeline ??= { drafts: [], queued_ideas: [] };
  state.pipeline.drafts.push({
    title: `${a.name} vs ${b.name} — deep dive`,
    path: `src/content/recipes/${filename}`,
    created: today,
  });
  await writeState(state);
  await recordRun('comparison', { pair: `${a.slug}-vs-${b.slug}` });

  console.log(`✓ Draft created: ${filepath}`);
  console.log('  Edit it, fill TODO markers, then commit.');
  console.log('  It will appear in the live site after next deploy.');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
